const fs = require('node:fs/promises');
const path = require('node:path');
const os = require('node:os');
const { execFileSync } = require('node:child_process');
const { gzipSync } = require('node:zlib');
const { makeBuilder, makeSculpt, KIT, PixelLook } = require('@shapeshift-labs/ink-studio').load();
const { geology } = require('./geology.cjs');
const { campModels } = require('./camp-models.cjs');

const project = path.join(__dirname, '..');
const modelDir = path.join(project, 'public', 'models');
const controls = process.argv.slice(2);
const storedStride = 11;

function bakeSplats(asset) {
  const colors = [0x1a2022];
  const indices = new Map([[colors[0], 0]]);
  const B = makeBuilder(4817, colors);
  const S = KIT.sculpt(makeSculpt(B));
  S.sun = B.norm([-.43, .74, .55]);
  S.amb = .22;
  S.sky = .23;
  S.sunK = .69;
  S.aoK = .92;
  S.shLen = 9;
  S.fat = .62;
  S.merge = true;
  const ink = {
    r: [0],
    tex(x, y, z, ny, light, nx, nz) {
      const base = asset.shade(x, y, z, nx, ny, nz);
      const grade = light < .25 ? .65 : light < .44 ? .83 : light < .80 ? 1 : 1.12;
      const shade = shift => Math.min(255, Math.round(((base >> shift) & 255) * grade));
      const rgb = (shade(16) << 16) | (shade(8) << 8) | shade(0);
      if (!indices.has(rgb)) {
        indices.set(rgb, colors.length);
        colors.push(rgb);
        B.P.push([shade(16), shade(8), shade(0)]);
      }
      return indices.get(rgb);
    },
  };
  S.implicitForm({ sd: (x, y, z) => asset.field([x, y, z]), bounds: asset.bounds }, ink, {
    res: asset.splatStep, cell: asset.splatStep * .85, maxWork: 10000000,
  });
  S.bake();
  const world = B.finish({ detail: 16, dither: .24, radius: 40 });
  if (!world.count) throw new Error('Empty Ink Studio splat asset ' + asset.name);
  const stored = new Float32Array(world.count * storedStride);
  for (let i = 0; i < world.count; i++) {
    const start = i * 16;
    stored.set(world.data.subarray(start, start + storedStride), i * storedStride);
  }
  return { name: asset.name, stored, count: world.count };
}

async function splats(assets) {
  const chunks = [];
  const index = [];
  let first = 0;
  for (const asset of assets) {
    const { name, stored, count } = bakeSplats(asset);
    index.push({ name, first, count });
    chunks.push(Buffer.from(stored.buffer));
    first += count;
    console.log(name + '  ' + count + ' Ink Studio Gaussians');
  }
  const header = Buffer.from(JSON.stringify({ version: 1, stride: storedStride, count: first, assets: index }));
  const prefix = Buffer.alloc(4 + Math.ceil(header.length / 4) * 4);
  prefix.writeUInt32LE(header.length, 0);
  header.copy(prefix, 4);
  const binary = gzipSync(Buffer.concat([prefix, ...chunks]), { level: 8 });
  await fs.writeFile(path.join(modelDir, 'coalfield.ink.gz'), binary);
  await fs.writeFile(path.join(project, 'src', 'board', 'ink-pixel.glsl'),
    '// PixelLook.glsl from Ink Studio (MIT, siliconjungle). Generated by npm run models.\n' + PixelLook.glsl + '\n');
  console.log('Gaussian transfer: ' + binary.length + ' bytes');
}

async function meshes(assets) {
  const THREE = await import('three');
  const { GLTFExporter } = await import('three/addons/exporters/GLTFExporter.js');
  global.FileReader = class {
    readAsArrayBuffer(blob) {
      blob.arrayBuffer().then(data => {
        this.result = data;
        this.onloadend?.();
      });
    }
  };
  const palette = new Map();
  const material = new THREE.MeshStandardMaterial({ vertexColors: true, roughness: .96 });
  const scenes = assets.map(({ name, field, bounds, meshStep: resolution, shade }) => {
    const { positions, normals } = KIT.procedural.geometry.implicitSurface(field, bounds, { resolution, maxCells: 310000 });
    if (!positions.length) throw new Error('Empty Ink Studio mesh ' + name);
    const colors = new Float32Array(positions.length);
    for (let i = 0; i < positions.length; i += 9) {
      const color = shade(
        (positions[i] + positions[i + 3] + positions[i + 6]) / 3,
        (positions[i + 1] + positions[i + 4] + positions[i + 7]) / 3,
        (positions[i + 2] + positions[i + 5] + positions[i + 8]) / 3, normals[i], normals[i + 1], normals[i + 2],
      );
      if (!palette.has(color)) palette.set(color, new THREE.Color(color).toArray());
      const rgb = palette.get(color);
      for (let vertex = i; vertex < i + 9; vertex += 3) colors.set(rgb, vertex);
    }
    const geometry = new THREE.BufferGeometry();
    geometry.setAttribute('position', new THREE.BufferAttribute(positions, 3));
    geometry.setAttribute('normal', new THREE.BufferAttribute(normals, 3));
    geometry.setAttribute('color', new THREE.BufferAttribute(colors, 3));
    const mesh = new THREE.Mesh(geometry, material);
    mesh.name = name;
    const scene = new THREE.Scene();
    scene.name = name;
    scene.add(mesh);
    return scene;
  });
  const glb = await new GLTFExporter().parseAsync(scenes, { binary: true });
  const temporary = await fs.mkdtemp(path.join(os.tmpdir(), 'ink-coalfield-'));
  const input = path.join(temporary, 'ink.glb');
  try {
    await fs.writeFile(input, Buffer.from(glb));
    execFileSync(process.execPath, [
      require.resolve('gltfpack/cli.js'), '-i', input, '-o', path.join(modelDir, 'coalfield.glb'),
      '-cc', '-ce', 'ext', '-kn', '-vpf', '-si', '0.58', '-se', '0.004', '-sp',
    ], { stdio: 'inherit' });
  } finally {
    await fs.rm(input, { force: true });
    await fs.rmdir(temporary);
  }
}

async function build() {
  const layout = await import('../src/board/locations.js');
  const { GOAL } = await import('../src/game-data.js');
  const { CRAFT_RECIPES } = await import('../src/legacy-cards.js');
  const assets = [...geology(KIT.procedural, layout, GOAL), ...campModels(CRAFT_RECIPES)];
  await fs.mkdir(modelDir, { recursive: true });
  if (!controls.includes('--meshes')) await splats(assets);
  if (!controls.includes('--splats')) await meshes(assets);
}

build().catch(error => {
  console.error(error);
  process.exitCode = 1;
});
