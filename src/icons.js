export function drawIcon(element, name = element.dataset.icon) {
  if (!icons[name] || element.dataset.drawn === name) return;
  const canvas = document.createElement('canvas');
  canvas.className = 'px-icon';
  canvas.width = canvas.height = 12;
  canvas.setAttribute('aria-hidden', 'true');
  const ctx = canvas.getContext('2d');
  icons[name].forEach((line, y) => [...line].forEach((pixel, x) => {
    if (!palette[pixel]) return;
    ctx.fillStyle = palette[pixel];
    ctx.fillRect(x, y, 1, 1);
  }));
  element.replaceChildren(canvas);
  element.dataset.drawn = name;
}
